// ══════════════════════════════════════════════════════════════
// FREE-TEXT QUALITY GUARDS
// ──────────────────────────────────────────────────────────────
// The old looksLikeGibberish() only caught extreme cases (a single
// repeated character, or a 6+ consonant run) and only looked at the
// run when the string had 5+ letters. That let obvious junk like
// "fdse21312", "asdasd", "qwerty" or "jkjk" straight through on the
// Full Name field, which then lands in the bookings table and on the
// crew slip the admin prints.
//
// Two levels are used now:
//   looksLikeGibberish()  — loose. For venue / event description,
//                           where digits, street numbers and brand
//                           names are all legitimate.
//   validatePersonName()  — strict. For "Full Name" only, where the
//                           value is known to be a human name, so we
//                           can require letters-only and real
//                           name-shaped words.
// Both are deliberately written to fail OPEN on anything ambiguous:
// blocking a real customer is a worse outcome than storing one odd
// name, so every rule below rejects only patterns that essentially
// never occur in a genuine Filipino/English name.
// ══════════════════════════════════════════════════════════════

// Keyboard runs — the single most common way a tester mashes a field.
const KEYBOARD_RUNS = [
  'qwertyuiop', 'asdfghjkl', 'zxcvbnm',
  '1234567890', 'qazwsxedc', 'poiuytrewq', 'lkjhgfdsa', 'mnbvcxz'
];

// Words that are never a real booking name, but pass every structural
// test because they are pronounceable.
const JUNK_WORDS = new Set([
  'test', 'testing', 'tester', 'testname', 'asdf', 'asdfg', 'asdfgh',
  'qwerty', 'qwertyui', 'sample', 'dummy', 'example', 'lorem', 'ipsum',
  'none', 'null', 'undefined', 'nil', 'na', 'nan', 'xxx', 'xxxx',
  'abc', 'abcd', 'abcde', 'aaa', 'zzz', 'blah', 'foo', 'bar', 'baz',
  'anonymous', 'anon', 'unknown', 'nothing', 'whatever', 'hello', 'hi'
]);

const VOWELS_RE = /[aeiouyàáâãäåèéêëìíîïòóôõöùúûüñ]/i;

function _normSpace(s) {
  return String(s || '').replace(/\s+/g, ' ').trim();
}

// True if the string contains a run of 4+ characters lying next to each
// other on the keyboard ("asdf", "qwer", "zxcv", "1234"), forwards or
// backwards.
function hasKeyboardRun(str) {
  const s = String(str || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  if (s.length < 4) return false;
  for (const row of KEYBOARD_RUNS) {
    for (let k = 0; k + 4 <= row.length; k++) {
      const seq = row.substring(k, k + 4);
      if (s.includes(seq)) return true;
      if (s.includes(seq.split('').reverse().join(''))) return true;
    }
  }
  return false;
}

// "abababab", "jkjkjk", "asdasdasd" — a short unit repeated to fill
// the field. Catches what a single-repeated-character test misses.
function hasRepeatedUnit(str) {
  const s = String(str || '').toLowerCase().replace(/\s/g, '');
  if (s.length < 4) return false;
  for (let unit = 1; unit <= 3; unit++) {
    if (s.length < unit * 2) continue;
    const head = s.substring(0, unit);
    if (head.repeat(Math.ceil(s.length / unit)).substring(0, s.length) === s) return true;
  }
  return false;
}

// Loose guard — free text that may legitimately contain digits and
// punctuation (venue, address, event description).
function looksLikeGibberish(str) {
  const val = _normSpace(str);
  if (val.length < 2) return false;            // required() handles emptiness
  const squashed = val.replace(/\s/g, '');

  if (/^(.)\1{2,}$/.test(squashed)) return true;   // "aaaaa", "11111"
  if (hasRepeatedUnit(squashed))    return true;   // "asdasdasd"
  if (hasKeyboardRun(squashed))     return true;   // "qwerty", "1234"

  const letters = squashed.replace(/[^a-zA-Z\u00c0-\u024f]/g, '');
  if (JUNK_WORDS.has(letters.toLowerCase())) return true;

  if (letters.length >= 4) {
    if (/[bcdfghjklmnpqrstvwxz]{5,}/i.test(letters)) return true;  // 5+ consonants
    if (!VOWELS_RE.test(letters)) return true;                     // no vowel at all
  }
  return false;
}

// Strict guard — "Full Name" only. Returns null when the value is
// acceptable, or a human-readable reason string when it is not.
//
// NOTE ON THE TWO-WORD RULE: the field is labelled "Full Name" and the
// booking confirmation, crew slip and SMS all address the customer by
// it, so a first name plus a surname is genuinely required. Set
// NAME_REQUIRE_TWO_PARTS = false below if a single-word entry should be
// allowed (e.g. for a mononym).
const NAME_REQUIRE_TWO_PARTS = true;

// Particles that are legitimately short and may be lowercase in
// Filipino/Spanish surnames — they are not counted as a "real" name part
// on their own, but they must not be rejected either.
const NAME_PARTICLES = new Set(['de', 'dela', 'del', 'della', 'di', 'da', 'las', 'los',
                                'la', 'van', 'von', 'bin', 'binti', 'al', 'st', 'sta',
                                'ng', 'y', 'jr', 'sr', 'ii', 'iii', 'iv']);

function validatePersonName(raw) {
  const val = _normSpace(raw);

  if (!val)             return 'Please enter your name.';
  if (val.length < 3)   return 'Please enter your full name (at least 3 characters).';
  if (val.length > 100) return 'That name is too long.';

  // Digits and symbols. This alone rejects "fdse21312", "john123",
  // "<script>", emails pasted into the wrong box, etc.
  if (/\d/.test(val))   return 'A name should not contain numbers.';
  if (!/^[\p{L}\p{M}][\p{L}\p{M} .'\u2019-]*$/u.test(val)) {
    return 'Use letters only — spaces, hyphens and apostrophes are fine.';
  }

  const low = val.toLowerCase();
  if (JUNK_WORDS.has(low.replace(/[^a-z]/g, ''))) return 'Please enter your real name.';
  if (hasKeyboardRun(val))   return 'Please enter your real name.';
  if (hasRepeatedUnit(val))  return 'Please enter your real name.';
  if (/(.)\1{2,}/.test(low.replace(/\s/g, ''))) return 'Please enter your real name.';

  // Word-level structure
  const parts = val.split(' ').filter(Boolean);
  let realParts = 0;

  for (const partRaw of parts) {
    const part = partRaw.replace(/[.'\u2019-]/g, '');
    const lowPart = part.toLowerCase();

    if (!part) continue;
    if (JUNK_WORDS.has(lowPart)) return 'Please enter your real name.';

    // A single letter is an initial ("Juan P. Cruz") — allowed, but it
    // doesn't count as one of the required name parts.
    if (part.length === 1) continue;

    if (NAME_PARTICLES.has(lowPart)) { continue; }

    // Every real name word has a vowel …
    if (!VOWELS_RE.test(part)) return 'Please enter your real name.';
    // … and no run of 4+ consonants inside it.
    if (/[bcdfghjklmnpqrstvwxz]{4,}/i.test(part)) return 'Please enter your real name.';
    // … and a sane vowel/consonant balance.
    const vowelCount = (part.match(/[aeiouy]/gi) || []).length;
    const ratio = vowelCount / part.length;
    if (part.length >= 4 && (ratio < 0.2 || ratio > 0.8)) return 'Please enter your real name.';

    realParts++;
  }

  if (realParts === 0) return 'Please enter your real name.';
  if (NAME_REQUIRE_TWO_PARTS && realParts < 2) {
    return 'Please enter your first name and surname.';
  }

  // "Juan Juan", "Cruz Cruz"
  const uniq = new Set(parts.map(p => p.toLowerCase()));
  if (parts.length > 1 && uniq.size === 1) return 'Please enter your real name.';

  return null;
}


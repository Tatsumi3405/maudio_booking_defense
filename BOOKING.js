// THEMED CALENDAR — Event Date field
// Replaces the native <input type="date"> with the MA Calendar
// widget. #eventDate stays in the DOM as a hidden input so every
// existing read (required(), goStep2(), submit payload) keeps
// working untouched.
// ══════════════════════════════════════════════════════════════
let _bookingCountsPromise = null;
function loadBookingCounts() {
  if (_bookingCountsPromise) return _bookingCountsPromise;
  _bookingCountsPromise = (async () => {
    const counts = {};
    try {
      const snap = await db.collection('booking_availability').get();
      snap.forEach(doc => {
        const d = doc.data();
        if (!d || d.status === 'cancelled' || !d.date) return;
        counts[d.date] = (counts[d.date] || 0) + 1;
      });
    } catch (e) { /* offline / no read access — fail open, calendar just shows no dots */ }
    return counts;
  })();
  return _bookingCountsPromise;
}

// Days the admin has manually blocked off (crew unavailable, holiday,
// double-booked elsewhere, etc. — not tied to any actual booking
// record). Set from the admin Calendar page; read here so those days
// show as unavailable on this public calendar too.
let _blockedDatesPromise = null;
function loadBlockedDates() {
  if (_blockedDatesPromise) return _blockedDatesPromise;
  _blockedDatesPromise = (async () => {
    const blocked = new Set();
    try {
      const snap = await db.collection('blocked_dates').get();
      snap.forEach(doc => blocked.add(doc.id));
    } catch (e) { /* table not set up yet, or offline — fail open */ }
    return blocked;
  })();
  return _blockedDatesPromise;
}

window.addEventListener('DOMContentLoaded', () => {
  const trigger = document.getElementById('eventDateTrigger');
  const textEl  = document.getElementById('eventDateText');
  const hidden  = document.getElementById('eventDate');
  if (!trigger || !hidden || !window.MACalendar) return;

  const today = new Date(); today.setHours(0, 0, 0, 0);

  new MACalendar({
    trigger, textEl, hiddenInput: hidden,
    mode: 'single',
    minDate: today,
    placeholder: 'Select event date',
    getDayMeta: async (date) => {
      const iso = MACalendar.toISO(date);
      const blocked = await loadBlockedDates();
      if (blocked.has(iso)) return { status: 'full', label: 'Not available for booking' };
      const counts = await loadBookingCounts();
      const n = counts[iso] || 0;
      if (n >= 3) return { status: 'full', label: 'Fully booked — all slots taken' };
      if (n >= 1) return { status: 'partial', label: n + ' slot(s) already booked this day' };
      return null;
    },
    onChange: () => {
      const err = document.getElementById('err-eventDate');
      if (err) err.textContent = '';
      // Verify the freshly-picked date against live data right away —
      // the calendar's own day-dots come from a promise cached at page
      // load, so a booking made in another tab won't be reflected there.
      // This gives the customer the answer while they're still looking
      // at the date field rather than four screens later.
      validateSelectedDate({ scrollTo: false });
    },
  });

  // Mirror .error from the hidden input onto the visible trigger so
  // required()/goStep2()'s existing validation still shows visually.
  new MutationObserver(() => {
    trigger.classList.toggle('error', hidden.classList.contains('error'));
  }).observe(hidden, { attributes: true, attributeFilter: ['class'] });
});
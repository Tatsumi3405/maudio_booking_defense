async function submitBooking() {
  let ok = true;
  ok = required('payMethod', 'err-payMethod', 'Please select a payment method.') && ok;

  const dpEl  = document.getElementById('downPayInput');
  const dpErr = document.getElementById('err-downPayInput');
  const dp    = parseFloat(dpEl.value);
  const total = window._finalTotal || 0;
  const minDown = Math.ceil(total * 0.10);

  if (!dpEl.value || isNaN(dp) || dp <= 0) {
    dpEl.classList.add('error'); dpErr.textContent = 'Please enter a down payment amount.'; ok = false;
  } else if (total > 0 && dp < minDown) {
    dpEl.classList.add('error'); dpErr.textContent = 'Minimum is ₱' + minDown.toLocaleString('en-PH') + '.'; ok = false;
  } else if (total > 0 && dp > total) {
    dpEl.classList.add('error'); dpErr.textContent = 'Cannot exceed ₱' + total.toLocaleString('en-PH') + '.'; dpEl.value = total; ok = false;
  } else { dpEl.classList.remove('error'); dpErr.textContent = ''; }

  const agree    = document.getElementById('agreeCheck');
  const agreeErr = document.getElementById('err-agree');
  if (!agree.checked) { agreeErr.textContent = 'Please agree to the booking terms.'; ok = false; }
  else agreeErr.textContent = '';
  if (!ok) return;

  // An upload may still be in flight if the customer dropped a file and
  // pressed SUBMIT immediately. Wait briefly (capped) so the booking row
  // carries the screenshot rather than silently losing it.
  if (window._uploadsPending > 0) {
    const waitStart = Date.now();
    while (window._uploadsPending > 0 && Date.now() - waitStart < 15000) {
      await new Promise(r => setTimeout(r, 250));
    }
  }

  const submitBtn = document.querySelector('[onclick="submitBooking()"]');
  if (submitBtn) { submitBtn.disabled = true; submitBtn.textContent = 'SUBMITTING…'; }

  const eventDate   = document.getElementById('eventDate').value;
  const pkgId       = selectedPkg?.id || (ledWallAddon?.id) || 'custom';
  const newSlotType = getSlotTypeForNew(pkgId);

  let slotCheck;
  try { slotCheck = await checkDaySlots(eventDate, newSlotType); }
  catch { slotCheck = { ok: true }; }

  if (!slotCheck.ok) {
    const ce = document.getElementById('slot-conflict-msg');
    if (ce) { ce.textContent = '⚠ ' + slotCheck.reason + ' Please go back and pick a different date.'; ce.style.display = 'block'; }
    if (submitBtn) { submitBtn.disabled = false; submitBtn.textContent = 'SUBMIT BOOKING REQUEST ✓'; }
    return;
  }

  const booking = {
    date:         eventDate,
    name:         clamp(document.getElementById('clientName').value, FIELD_LIMITS.clientName),
    pkg:          clamp(window._pkgLabel || '—', FIELD_LIMITS.pkg),
    pkgId:        pkgId,
    eventName:    clamp(document.getElementById('eventName').value, FIELD_LIMITS.eventName),
    eventType:    document.getElementById('eventType')?.value || activeCategory,
    venue:        clamp(document.getElementById('eventVenue').value, FIELD_LIMITS.eventVenue),
    crowd:        document.getElementById('crowdSize').value,
    time:         document.getElementById('eventTime').value,
    duration:     document.getElementById('eventDuration').value,
    phone:        clamp(document.getElementById('clientPhone').value, FIELD_LIMITS.clientPhone),
    email:        clamp(document.getElementById('clientEmail').value, FIELD_LIMITS.clientEmail),
    fb:           clamp(document.getElementById('clientFB').value, FIELD_LIMITS.clientFB),
    contactPref:  document.getElementById('contactMethod').value,
    notes:        (() => {
      const baseNotes = clamp(document.getElementById('eventNotes').value, FIELD_LIMITS.eventNotes);
      const payRef    = clamp(document.getElementById('payNotes')?.value || '', FIELD_LIMITS.payNotes);
      if (payRef) return baseNotes ? baseNotes + '\n\nPayment Reference: ' + payRef : 'Payment Reference: ' + payRef;
      return baseNotes;
    })(),
    poster:       document.getElementById('posterCheck').checked,
    posterDesc:   clamp(document.getElementById('posterDetails').value, FIELD_LIMITS.posterDesc),
    payMethod:    document.getElementById('payMethod').value,
    downPay:      dp,
    totalPrice:   total,
    crewCount:    window._crewCount || selectedCrewCount,
    mealProvided: window._mealProvided !== false,
    mealCost:     window._mealCost || 0,
    mealMeals:    mealCount,
    addons:       clamp(window._addonParts?.join(', ') || '', FIELD_LIMITS.addons),
    ledWall:      window._ledWallAddon ? clamp(`${window._ledWallAddon.panels} panels (${window._ledWallAddon.location})`, FIELD_LIMITS.ledWall) : '',
    onlinePayment: ['GCash (InstaPay to BPI)', 'BPI Bank Transfer (InstaPay)'].includes(document.getElementById('payMethod').value),
    // Screenshot uploads (MA_UPLOAD.js). Stored as the storage object
    // path — the admin panel mints a short-lived signed URL from it,
    // so the image is never readable by an anonymous visitor.
    socialProof:   window._uploads?.social?.path  || '',
    paymentProof:  window._uploads?.payment?.path || '',
    // True only when we still need a screenshot from them: they paid
    // online but didn't attach anything.
    proofRequired: !!document.getElementById('payMethod')?.value &&
                   ['GCash (InstaPay to BPI)', 'BPI Bank Transfer (InstaPay)']
                     .includes(document.getElementById('payMethod').value) &&
                   !window._uploads?.payment?.path,
    slotType:     newSlotType,
    status:       'pending',
    submitted:    serverTimestamp(),
  };

  try {
    const docRef = await db.collection('bookings').addPublic(booking);
    verifyBookingPrice(docRef.id); // fire-and-forget — see function comment
    const ref = 'MA-' + new Date().getFullYear() + '-' + docRef.id.substring(0,6).toUpperCase();
    document.getElementById('successRef').textContent = 'REF: ' + ref;
    document.getElementById('formSection').style.display = 'none';
    document.getElementById('successScreen').classList.add('visible');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  } catch (err) {
    console.error('Booking save error:', err);
    if (submitBtn) { submitBtn.disabled = false; submitBtn.textContent = 'SUBMIT BOOKING REQUEST ✓'; }
    let errMsg = err?.message || err?.error_description || JSON.stringify(err);
    // The database enforces slot rules too (see SECURITY_MIGRATION.sql).
    // If someone else grabbed the slot between the check above and this
    // insert, turn the raw DB error into a plain message.
    const dbRule = /^(SLOT_TAKEN|DATE_FULL|DATE_BLOCKED):\s*(.*)$/.exec(errMsg);
    if (dbRule) errMsg = dbRule[2] + ' Please go back and pick a different date.';
    const ceEl = document.getElementById('slot-conflict-msg');
    if (ceEl) {
      // SECURITY FIX: errMsg comes straight off the database/network error
      // object, so it must never be concatenated into innerHTML. Build the
      // node structure here and set the untrusted part with textContent,
      // which cannot introduce markup.
      ceEl.textContent = '';
      const ceTitle = document.createElement('strong');
      ceTitle.textContent = '❌ Submission failed:';
      const ceBody = document.createElement('span');
      ceBody.textContent = ' ' + errMsg;
      const ceHint = document.createElement('small');
      ceHint.style.opacity = '.7';
      ceHint.textContent = 'Check your connection or contact us on Facebook.';
      ceEl.appendChild(ceTitle);
      ceEl.appendChild(ceBody);
      ceEl.appendChild(document.createElement('br'));
      ceEl.appendChild(ceHint);
      ceEl.style.display = 'block';
      ceEl.style.background = 'rgba(232,24,12,0.1)';
      ceEl.style.border = '1px solid rgba(232,24,12,0.35)';
      ceEl.style.borderRadius = '8px';
      ceEl.style.padding = '.85rem 1rem';
      ceEl.style.color = '#f87171';
      ceEl.style.fontFamily = 'var(--font-m, monospace)';
      ceEl.style.fontSize = '.75rem';
      ceEl.style.lineHeight = '1.7';
      setTimeout(() => ceEl.scrollIntoView({ behavior: 'smooth', block: 'center' }), 100);
    } else {
      alert('Submission failed: ' + errMsg);
    }
  }
};


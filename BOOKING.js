function initSelector() {
  renderCategoryTabs();
  switchCategory('basic');
}

function renderCategoryTabs() {
  const tabsEl = document.getElementById('pkgCatTabs');
  if (!tabsEl) return;
  tabsEl.innerHTML = Object.entries(PACKAGE_DATA).map(([key, cat]) =>
    `<button class="pkg-cat-tab ${key === activeCategory ? 'active' : ''}"
      onclick="switchCategory('${key}')">
      <span class="pct-icon">${cat.icon}</span>
      <span class="pct-label">${cat.label}</span>
    </button>`
  ).join('');
}

function switchCategory(catKey) {
  activeCategory = catKey;
  // Update tab active state
  document.querySelectorAll('.pkg-cat-tab').forEach(t =>
    t.classList.toggle('active', t.onclick.toString().includes(`'${catKey}'`))
  );
  renderPackageCards(catKey);
  // Reset selection if switching category
  if (selectedPkg && !selectedPkg.id.startsWith(catKey.substring(0,3))) {
    selectedPkg = null;
    updateStickyBar();
  }
}

function renderPackageCards(catKey) {
  const cat    = PACKAGE_DATA[catKey];
  const el     = document.getElementById('pkgCardsWrap');
  if (!el) return;

  // Crew badge
  document.getElementById('pkgCrewNote').innerHTML =
    `<span class="crew-badge">👥 ${cat.crew} crew members included</span>` +
    `<span class="crew-note"> · All packages include full setup &amp; teardown</span>`;

  if (catKey === 'ledwall') {
    el.innerHTML = cat.packages.map(pkg => renderLedWallCard(pkg)).join('');
    el.className = 'pkg-cards-grid ledwall-grid';
  } else {
    el.innerHTML = cat.packages.map(pkg => renderPackageCard(pkg, cat)).join('');
    el.className = 'pkg-cards-grid';
  }
}

function renderPackageCard(pkg, cat) {
  const isSelected = selectedPkg && selectedPkg.id === pkg.id;
  const tag = pkg.tag ? `<span class="pkg-card-tag">${pkg.tag}</span>` : '';
  return `<div class="pkg-sel-card ${isSelected ? 'selected' : ''}" id="pcard-${pkg.id}" onclick="selectPackage('${pkg.id}')">
    ${tag}
    <div class="pkg-sel-num">PKG ${pkg.num}</div>
    <div class="pkg-sel-price"><span class="pkg-sel-currency">₱</span>${pkg.price.toLocaleString('en-PH')}</div>
    <ul class="pkg-sel-list">
      ${pkg.inclusions.map(i => `<li>${i}</li>`).join('')}
    </ul>
    <div class="pkg-sel-footer">
      <span class="pkg-sel-crew">👥 ${cat.crew} crew</span>
      <button class="pkg-sel-btn ${isSelected ? 'selected' : ''}" onclick="event.stopPropagation();selectPackage('${pkg.id}')">
        ${isSelected ? '✓ SELECTED' : 'SELECT'}
      </button>
    </div>
  </div>`;
}


// DATE AVAILABILITY
// ──────────────────────────────────────────────────────────────
// Previously the only hard availability check lived inside
// submitBooking(), i.e. the customer filled in the entire form and
// only learned at the payment step that the date was already gone.
// The check now runs at every point where the customer moves forward:
//
//   1. the moment a date is picked on the calendar   (live feedback)
//   2. Step 1 → Step 2   (goStep2)
//   3. Step 2 → Step 3   (goStep3)
//   4. final submit      (submitBooking — unchanged, still the
//                         authoritative gate against a race)
//
// It also now honours the admin's manually-blocked days
// (`blocked_dates`), which the old check ignored entirely — so a day
// the admin had explicitly closed was still bookable from this form.
// ══════════════════════════════════════════════════════════════

// ══════════════════════════════════════════════════════════════
// SLOT CATEGORIES
// ──────────────────────────────────────────────────────────────
// There are three slots per day, and each may be taken once:
//
//   'pa'      — shared by BASIC PA, WEDDING, BIG CROWD, and CUSTOM.
//               Any one booking from those four categories consumes
//               the PA slot for that date; a second booking from
//               another of those categories on the same day is
//               rejected. (They used to be three separate slots —
//               'pa' / 'wedding' / 'bigcrowd' — which let a single
//               day quietly hold a wedding AND a big-crowd event.
//               They now compete for the same slot.)
//
//   'ledwall' — LED WALL packages only. Bookable once per day.
//
//   'disco'   — DISCO package only. Bookable once per day.
//
// The primary package decides the slot. An LED-Wall add-on on top of
// a PA package does not consume the LED Wall slot — only a booking
// whose *primary* package is LED Wall does.
// ══════════════════════════════════════════════════════════════
function getSlotTypeForNew(pkgId, categoryHint) {
  const cat = String(categoryHint || activeCategory || '').toLowerCase();
  const id  = String(pkgId || '').toLowerCase();

  // LED Wall — own slot
  if (id.startsWith('lw') || cat === 'ledwall') return 'ledwall';

  // Disco — own slot
  if (id === 'disco' || cat === 'disco') return 'disco';

  // Everything else (basic, wedding, bigcrowd, custom) shares the
  // single PA slot.
  return 'pa';
}

// Authoritative check. Reads both `blocked_dates` (admin-blocked days)
// and `booking_availability` (live slot usage) fresh from the database
// every time — never from cache — so a booking made two minutes ago by
// someone else is always reflected.
//
// Legacy slot types from before this update (`'wedding'`, `'bigcrowd'`)
// are folded into `'pa'` on read, so a booking made under the old
// scheme still correctly blocks the PA slot today.
async function checkDaySlots(date, newSlotType) {
  if (!date) return { ok: false, reason: 'Please pick a date.' };

  // Normalise legacy values. A booking stored with slottype 'wedding'
  // or 'bigcrowd' now occupies the shared 'pa' slot.
  const SLOT_ALIAS = {
    pa: 'pa', wedding: 'pa', bigcrowd: 'pa',
    ledwall: 'ledwall', disco: 'disco',
  };
  const target = SLOT_ALIAS[String(newSlotType || '').toLowerCase()] || 'pa';

  try {
    // 1. Admin-blocked day (Calendar → "Block this day")
    const blockedDoc = await db.collection('blocked_dates')
      .doc(date).get()
      .catch(() => ({ exists: false }));
    if (blockedDoc && blockedDoc.exists) {
      return { ok: false, reason: 'This date is not open for booking. Please pick another date.' };
    }

    // 2. Live slot usage for the day
    const snap = await db.collection('booking_availability')
      .where('date', '==', date).get();
    const counts = { pa: 0, ledwall: 0, disco: 0 };
    snap.forEach(doc => {
      const d = doc.data();
      if (d.status === 'cancelled') return;
      const raw  = String(d.slottype || 'pa').toLowerCase();
      const norm = SLOT_ALIAS[raw] || 'pa';
      if (norm in counts) counts[norm]++;
    });

    if (counts[target] >= 1) {
      const labels = {
        pa:      'PA / Wedding / Big Crowd slot',
        ledwall: 'LED Wall slot',
        disco:   'Disco slot',
      };
      return { ok: false, reason: (labels[target] || 'slot') + ' is already taken for this date.' };
    }
    return { ok: true };
  } catch {
    // Transient read error — fail OPEN rather than blocking a real customer.
    return { ok: true };
  }
}

// ── Single entry point used by every point in the flow ────────
// Reads the currently-selected date, works out which slot this
// customer's package occupies, checks it, and paints the result onto
// the date field. Returns { ok, reason }.
let _dateCheckSeq = 0;

function invalidateAvailabilityCaches() {
  // The calendar caches its day-counts / blocked-days promises for the
  // lifetime of the page. Once we know a day is gone, drop the cache so
  // the next time the picker opens it re-reads the database.
  _bookingCountsPromise = null;
  _blockedDatesPromise  = null;
}

async function validateSelectedDate(opts) {
  opts = opts || {};
  const dateEl = document.getElementById('eventDate');
  const errEl  = document.getElementById('err-eventDate');
  const trigger= document.getElementById('eventDateTrigger');
  const date   = dateEl ? dateEl.value : '';
  if (!date) return { ok: false, reason: 'Please pick a date.' };

  const seq      = ++_dateCheckSeq;
  const pkgId    = (selectedPkg && selectedPkg.id) || (ledWallAddon && ledWallAddon.id) || 'custom';
  const slotType = getSlotTypeForNew(pkgId);

  if (opts.onChecking) opts.onChecking();
  const res = await checkDaySlots(date, slotType);

  // A newer check started while this one was in flight — discard the
  // stale result so a slow first response can't overwrite a fast second.
  if (seq !== _dateCheckSeq) return { ok: true };

  if (res.ok) {
    if (errEl)   errEl.textContent = '';
    if (dateEl)  dateEl.classList.remove('error');
    if (trigger) trigger.classList.remove('error');
    hideDateConflictBanner();
  } else {
    if (errEl)   errEl.textContent = res.reason;
    if (dateEl)  dateEl.classList.add('error');
    if (trigger) trigger.classList.add('error');
    invalidateAvailabilityCaches();
    if (opts.scrollTo && trigger) {
      trigger.scrollIntoView({ behavior: 'smooth', block: 'center' });
    }
  }
  return res;
}

